#!/usr/bin/env python3
"""Embed GLSL shaders of the program (not of the game's zones) in a C++ header, in the forms the backends take.

    tools/embed_shaders.py OUT_HEADER --namespace NS --macro PREFIX [--glsl] [--uam PATH] [--glslang PATH]
                           NAME=FILE:STAGE ...

STAGE is vert or frag. For each shader the header holds, in namespace NS:
- kGlsl<NAME>, its text, with --glsl (the GL backend compiles it at run time);
- kDksh<NAME>, deko3d DKSH from uam, with --uam (the Switch build), and PREFIX_HAS_DKSH is defined;
- kSpirv<NAME>, Vulkan SPIR-V from glslang, with --glslang, and PREFIX_HAS_SPIRV is defined. It is compiled as
  tools/ffconv/gen/make_spirv_pack.py compiles shaders.pack (Vulkan 1.1, uniform blocks moved to binding 16 + their
  GL binding), so a shader written to the pack's interface keeps it.

Users: the D3D9 frontend's upscaler (src/gfx_d3d9emu/shaders) and the Vulkan backend's own shaders
(src/gfx_backend/vulkan/shaders). The header is rewritten only when its text changes, so an unchanged build
recompiles nothing.
"""
import argparse
import os
import platform
import shutil
import subprocess
import sys
import tempfile

STAGES = ('vert', 'frag')
# uam's output depends on where its heap lands (make_dksh_pack.py): without address randomisation it is reproducible.
NO_ASLR = ['setarch', platform.machine(), '-R'] if shutil.which('setarch') else []
SPIRV_ARGS = ['-V', '--target-env', 'vulkan1.1', '--shift-UBO-binding', '16']


def array(name, data):
    lines = [f'inline constexpr unsigned char k{name}[] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def run(command, src, out):
    proc = subprocess.run(command, capture_output=True, text=True)
    if proc.returncode or not os.path.exists(out):
        raise SystemExit(f'{command[0]} rejected {src}:\n{(proc.stdout + proc.stderr).strip()}')
    with open(out, 'rb') as f:
        return f.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('out_header')
    parser.add_argument('--namespace', required=True)
    parser.add_argument('--macro', required=True)
    parser.add_argument('--glsl', action='store_true')
    parser.add_argument('--uam')
    parser.add_argument('--glslang')
    parser.add_argument('shaders', nargs='+', metavar='NAME=FILE:STAGE')
    opts = parser.parse_args()

    shaders = []
    for spec in opts.shaders:
        name, _, rest = spec.partition('=')
        path, _, stage = rest.rpartition(':')
        if not name or not path or stage not in STAGES:
            raise SystemExit(f'{spec}: want NAME=FILE:STAGE with STAGE vert or frag')
        shaders.append((name, path, stage))

    parts = ['// Generated by tools/embed_shaders.py: do not edit.', '#pragma once', '']
    if opts.uam:
        parts.append(f'#define {opts.macro}_HAS_DKSH 1')
    if opts.glslang:
        parts.append(f'#define {opts.macro}_HAS_SPIRV 1')
    parts += ['', f'namespace {opts.namespace}', '{']
    with tempfile.TemporaryDirectory() as work:
        for name, path, stage in shaders:
            if opts.glsl:
                with open(path, 'rb') as f:
                    parts.append(array('Glsl' + name, f.read()))
            out = os.path.join(work, name)
            if opts.uam:
                command = NO_ASLR + [opts.uam, '-s', stage, path, '-o', out + '.dksh']
                parts.append(array('Dksh' + name, run(command, path, out + '.dksh')))
            if opts.glslang:
                command = [opts.glslang] + SPIRV_ARGS + ['-S', stage, path, '-o', out + '.spv']
                parts.append(array('Spirv' + name, run(command, path, out + '.spv')))
    parts.append(f'}} // namespace {opts.namespace}')
    text = '\n'.join(parts) + '\n'

    try:
        with open(opts.out_header, encoding='ascii') as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(opts.out_header)), exist_ok=True)
    with open(opts.out_header, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
