#!/usr/bin/env python3
"""Embed the D3D9 frontend's upscaler shaders (src/gfx_d3d9emu/shaders/fsr1_*.glsl) in a C++ header.

    tools/upscale_shaders.py SHADER_DIR OUT_HEADER [--uam PATH]

The header holds each shader's GLSL, which the GL backend compiles at run time; with --uam (the Switch build) it also
holds each one compiled to deko3d DKSH by uam, as tools/ffconv/gen/make_dksh_pack.py compiles shaders.pack. The
frontend hands the backend the form its shaders.pack carries (d3d9emu_upscale.cpp). The header is rewritten only when
its text changes, so an unchanged build recompiles nothing.
"""
import argparse
import os
import platform
import shutil
import subprocess
import sys
import tempfile

# (name in the header, file, uam stage)
SHADERS = [('Vs', 'fsr1_vs.glsl', 'vert'), ('Easu', 'fsr1_easu.glsl', 'frag'), ('Rcas', 'fsr1_rcas.glsl', 'frag')]

# uam's output depends on where its heap lands (make_dksh_pack.py): without address randomisation it is reproducible.
NO_ASLR = ['setarch', platform.machine(), '-R'] if shutil.which('setarch') else []


def array(name, data):
    lines = [f'inline constexpr unsigned char k{name}[] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def compile_dksh(uam, src, stage, work):
    dst = os.path.join(work, os.path.basename(src) + '.dksh')
    proc = subprocess.run(NO_ASLR + [uam, '-s', stage, src, '-o', dst], capture_output=True, text=True)
    if proc.returncode or not os.path.exists(dst):
        raise SystemExit(f'uam rejected {src}:\n{(proc.stderr or proc.stdout).strip()}')
    with open(dst, 'rb') as f:
        return f.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('shader_dir')
    parser.add_argument('out_header')
    parser.add_argument('--uam')
    opts = parser.parse_args()

    parts = ['// Generated by tools/upscale_shaders.py from src/gfx_d3d9emu/shaders: do not edit.', '#pragma once', '',
             'namespace d3d9emu::upscale_shaders', '{']
    with tempfile.TemporaryDirectory() as work:
        for name, file, stage in SHADERS:
            path = os.path.join(opts.shader_dir, file)
            with open(path, 'rb') as f:
                parts.append(array('Glsl' + name, f.read()))
            if opts.uam:
                parts.append(array('Dksh' + name, compile_dksh(opts.uam, path, stage, work)))
    parts.append('} // namespace d3d9emu::upscale_shaders')
    if opts.uam:
        parts.insert(2, '#define BO1_UPSCALE_HAS_DKSH 1')
    text = '\n'.join(parts) + '\n'

    try:
        with open(opts.out_header, encoding='ascii') as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(opts.out_header)), exist_ok=True)
    with open(opts.out_header, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
